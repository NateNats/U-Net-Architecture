class ActivationCAM:
    """
    Activation-based CAM untuk U-Net: Extract attention maps dari model.
    Menunjukkan region mana yang penting untuk prediksi model.
    Menggunakan activation maps tanpa backward pass (lebih stabil).
    """
    def __init__(self, model, target_layer):
        """
        Args:
            model: PyTorch model
            target_layer: Layer untuk extract activation (string atau module)
        """
        self.model = model
        self.activations = None
        
        # Register hooks
        if isinstance(target_layer, str):
            target_module = dict([*self.model.named_modules()])[target_layer]
        else:
            target_module = target_layer
            
        target_module.register_forward_hook(self.save_activation)
    
    def save_activation(self, module, input, output):
        self.activations = output.detach()
    
    def generate_cam(self, input_tensor):
        """
        Generate Class Activation Map menggunakan activation strengths.
        
        Args:
            input_tensor: Input image (B, C, H, W)
        
        Returns:
            cam: Attention map (H, W)
        """
        # Forward pass
        with torch.no_grad():
            _ = self.model(input_tensor)
        
        # Compute CAM dari activations
        activations = self.activations[0]  # (C, H, W)
        
        # Weight by channel importance (mean of each channel)
        weights = activations.mean(dim=(1, 2))  # (C,)
        weights = F.softmax(weights, dim=0)
        
        cam = (weights.view(-1, 1, 1) * activations).sum(dim=0)  # (H, W)
        
        # Normalize dan apply ReLU
        cam = F.relu(cam)
        cam = (cam - cam.min()) / (cam.max() - cam.min() + 1e-8)
        
        return cam.cpu().numpy()


def compute_quality_distribution(model, test_loader, device='cuda'):
    """
    Compute Dice dan IoU scores untuk setiap image di dataset.
    
    Args:
        model: U-Net model (already loaded)
        test_loader: DataLoader untuk test/validation set
        device: 'cuda' atau 'cpu'
    
    Returns:
        dict dengan 'dice' dan 'iou' scores per image
    """
    from utils.metrics import SegmentationMetrics
    
    model.eval()
    model.to(device)
    
    dice_scores = []
    iou_scores = []
    metrics_fn = SegmentationMetrics(threshold=0.5)
    
    with torch.no_grad():
        for images, masks in test_loader:
            images = images.to(device)
            masks = masks.to(device)
            
            logits = model(images)
            metrics = metrics_fn.compute(logits, masks)
            
            dice_scores.append(metrics['dice'])
            iou_scores.append(metrics['iou'])
    
    return {
        'dice': dice_scores,
        'iou': iou_scores,
        'mean_dice': np.mean(dice_scores),
        'std_dice': np.std(dice_scores),
        'mean_iou': np.mean(iou_scores),
        'std_iou': np.std(iou_scores),
    }


def plot_quality_distribution(quality_metrics, title="Segmentation Quality Distribution", save_path=None):
    """
    Plot distribusi Dice dan IoU scores.
    
    Args:
        quality_metrics: Output dari compute_quality_distribution()
        title: Judul plot
        save_path: Path untuk save figure (optional)
    """
    fig, axes = plt.subplots(2, 2, figsize=(14, 10), facecolor='white')
    fig.suptitle(title, fontsize=16, fontweight='bold')
    
    # Histogram Dice
    axes[0, 0].hist(quality_metrics['dice'], bins=20, color='skyblue', edgecolor='black', alpha=0.7)
    axes[0, 0].axvline(quality_metrics['mean_dice'], color='red', linestyle='--', linewidth=2.5,
                       label=f"Mean: {quality_metrics['mean_dice']:.3f}")
    axes[0, 0].set_title('Dice Score Distribution', fontweight='bold', fontsize=12)
    axes[0, 0].set_xlabel('Dice Score', fontsize=11)
    axes[0, 0].set_ylabel('Frequency', fontsize=11)
    axes[0, 0].legend(fontsize=10)
    axes[0, 0].grid(True, alpha=0.3)
    axes[0, 0].set_facecolor('white')
    
    # Histogram IoU
    axes[0, 1].hist(quality_metrics['iou'], bins=20, color='lightcoral', edgecolor='black', alpha=0.7)
    axes[0, 1].axvline(quality_metrics['mean_iou'], color='darkred', linestyle='--', linewidth=2.5,
                       label=f"Mean: {quality_metrics['mean_iou']:.3f}")
    axes[0, 1].set_title('IoU Score Distribution', fontweight='bold', fontsize=12)
    axes[0, 1].set_xlabel('IoU Score', fontsize=11)
    axes[0, 1].set_ylabel('Frequency', fontsize=11)
    axes[0, 1].legend(fontsize=10)
    axes[0, 1].grid(True, alpha=0.3)
    axes[0, 1].set_facecolor('white')
    
    # Box plot Dice
    bp1 = axes[1, 0].boxplot(quality_metrics['dice'], vert=True, patch_artist=True)
    for patch in bp1['boxes']:
        patch.set_facecolor('skyblue')
    axes[1, 0].set_title('Dice Score Box Plot', fontweight='bold', fontsize=12)
    axes[1, 0].set_ylabel('Dice Score', fontsize=11)
    axes[1, 0].grid(True, alpha=0.3, axis='y')
    axes[1, 0].set_facecolor('white')
    
    # Box plot IoU
    bp2 = axes[1, 1].boxplot(quality_metrics['iou'], vert=True, patch_artist=True)
    for patch in bp2['boxes']:
        patch.set_facecolor('lightcoral')
    axes[1, 1].set_title('IoU Score Box Plot', fontweight='bold', fontsize=12)
    axes[1, 1].set_ylabel('IoU Score', fontsize=11)
    axes[1, 1].grid(True, alpha=0.3, axis='y')
    axes[1, 1].set_facecolor('white')
    
    plt.tight_layout()
    
    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches='tight', facecolor='white')
        print(f"✓ Quality distribution plot saved to: {save_path}")
    
    plt.show()
    
    # Print statistik
    print(f"\n{'='*50}")
    print(f"SEGMENTATION QUALITY STATISTICS")
    print(f"{'='*50}")
    print(f"Dice Score:")
    print(f"  Mean:     {quality_metrics['mean_dice']:.4f}")
    print(f"  Std Dev:  {quality_metrics['std_dice']:.4f}")
    print(f"  Min:      {np.min(quality_metrics['dice']):.4f}")
    print(f"  Max:      {np.max(quality_metrics['dice']):.4f}")
    print(f"\nIoU Score:")
    print(f"  Mean:     {quality_metrics['mean_iou']:.4f}")
    print(f"  Std Dev:  {quality_metrics['std_iou']:.4f}")
