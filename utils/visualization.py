def visualize_single_cam(model, image, mask=None, target_layer='bottleneck', 
                         device='cuda' if torch.cuda.is_available() else 'cpu'):
    """
    Visualisasi CAM untuk single image.
    
    Args:
        model: U-Net model
        image: Input image (H, W, 3) normalized
        mask: Ground truth mask (H, W), optional
        target_layer: Layer untuk extract CAM
        device: 'cuda' atau 'cpu'
    """
    # Setup
    model.eval()
    model.to(device)
    cam_extractor = ActivationCAM(model, target_layer)
    
    # Prepare input
    if isinstance(image, np.ndarray):
        image_tensor = torch.from_numpy(image).permute(2, 0, 1).unsqueeze(0).float().to(device)
    else:
        image_tensor = image.unsqueeze(0).to(device)
    
    # Generate CAM
    with torch.no_grad():
        cam = cam_extractor.generate_cam(image_tensor)
    
    # Resize CAM ke ukuran original image
    cam_resized = cv2.resize(cam, (image.shape[1], image.shape[0]))
    cam_resized = gaussian_filter(cam_resized, sigma=1.5)  # Smooth
    
    # Prepare plots
    n_plots = 3 if mask is None else 4
    fig, axes = plt.subplots(1, n_plots, figsize=(15, 4), facecolor='white')
    
    # Original image
    if len(image.shape) == 3 and image.shape[2] == 3:
        axes[0].imshow(image)
    else:
        axes[0].imshow(image, cmap='gray')
    axes[0].set_title('Original Image', fontweight='bold')
    axes[0].axis('off')
    
    # CAM heatmap
    im = axes[1].imshow(cam_resized, cmap='jet')
    axes[1].set_title('Grad-CAM (Attention)', fontweight='bold')
    axes[1].axis('off')
    plt.colorbar(im, ax=axes[1], fraction=0.046)
    
    # CAM overlay pada image
    if len(image.shape) == 3 and image.shape[2] == 3:
        overlay = image.copy()
    else:
        overlay = cv2.cvtColor((image * 255).astype(np.uint8), cv2.COLOR_GRAY2RGB) / 255.0
    
    cam_color = cv2.applyColorMap((cam_resized * 255).astype(np.uint8), cv2.COLORMAP_JET)
    cam_color = cv2.cvtColor(cam_color, cv2.COLOR_BGR2RGB) / 255.0
    overlay_blend = 0.6 * overlay + 0.4 * cam_color
    
    axes[2].imshow(overlay_blend)
    axes[2].set_title('Overlay', fontweight='bold')
    axes[2].axis('off')
    
    # Ground truth mask (jika ada)
    if mask is not None:
        axes[3].imshow(mask, cmap='RdYlGn', alpha=0.7)
        axes[3].set_title('Ground Truth Mask', fontweight='bold')
        axes[3].axis('off')
    
    plt.tight_layout()
    plt.show()


def visualize_multiple_cams(model, dataset, num_samples=6, target_layer='bottleneck',
                           device='cuda' if torch.cuda.is_available() else 'cpu', save_path=None):
    """
    Visualisasi CAM untuk multiple samples dari dataset.
    
    Args:
        model: U-Net model
        dataset: ISICDataset instance
        num_samples: Jumlah samples untuk visualisasi
        target_layer: Layer untuk extract CAM
        device: Device untuk inference
        save_path: Path untuk save figure (optional)
    """
    model.eval()
    model.to(device)
    cam_extractor = ActivationCAM(model, target_layer)
    
    # Ambil random samples
    indices = np.random.choice(len(dataset), min(num_samples, len(dataset)), replace=False)
    
    fig, axes = plt.subplots(num_samples, 4, figsize=(16, 4*num_samples), facecolor='white')
    if num_samples == 1:
        axes = axes.reshape(1, -1)
    
    fig.suptitle('Grad-CAM Visualizations', fontsize=16, fontweight='bold')
    
    with torch.no_grad():
        for row, idx in enumerate(indices):
            image, mask = dataset[idx]
            image_np = image.permute(1, 2, 0).numpy()
            mask_np = mask.numpy()
            
            # Generate CAM
            image_tensor = image.unsqueeze(0).to(device)
            cam = cam_extractor.generate_cam(image_tensor)
            
            cam_resized = cv2.resize(cam, (image_np.shape[1], image_np.shape[0]))
            cam_resized = gaussian_filter(cam_resized, sigma=1.5)
            
            # Original
            axes[row, 0].imshow(image_np)
            axes[row, 0].set_title(f'Image {idx}', fontweight='bold', fontsize=10)
            axes[row, 0].axis('off')
            
            # CAM
            im = axes[row, 1].imshow(cam_resized, cmap='jet')
            axes[row, 1].set_title('Grad-CAM', fontweight='bold', fontsize=10)
            axes[row, 1].axis('off')
            
            # Overlay
            overlay = image_np.copy()
            cam_color = cv2.applyColorMap((cam_resized * 255).astype(np.uint8), cv2.COLORMAP_JET)
            cam_color = cv2.cvtColor(cam_color, cv2.COLOR_BGR2RGB) / 255.0
            overlay_blend = 0.6 * overlay + 0.4 * cam_color
            axes[row, 2].imshow(overlay_blend)
            axes[row, 2].set_title('Overlay', fontweight='bold', fontsize=10)
            axes[row, 2].axis('off')
            
            # Ground truth
            axes[row, 3].imshow(mask_np, cmap='RdYlGn', alpha=0.7)
            axes[row, 3].set_title('Ground Truth', fontweight='bold', fontsize=10)
            axes[row, 3].axis('off')
    
    plt.tight_layout()
    
    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches='tight', facecolor='white')
        print(f"✓ CAM visualization saved to: {save_path}")
    
    plt.show()
